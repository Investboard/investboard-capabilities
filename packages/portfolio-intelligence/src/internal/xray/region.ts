export function countryToRegion(
	isoAlpha2: string | null | undefined,
): XrayRegion {
	const code = isoAlpha2?.trim().toUpperCase();
	if (!code) return "other";
	return (Object.hasOwn(MAP, code) ? MAP[code] : undefined) ?? "other";
}
